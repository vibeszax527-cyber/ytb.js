	onStart: async function ({ api, args, event, message, commandName, usersData }) {
		const { threadID, messageID, senderID } = event;

		let type;
		switch (args[0]) {
			case "-v":
			case "video":
				type = "video";
				break;
			case "-a":
			case "-s":
			case "audio":
			case "sing":
				type = "audio";
				break;
			case "-i":
			case "info":
				type = "info";
				break;
			default:
				return message.SyntaxError();
		}

		const input = args.slice(1).join(" ").trim();
		if (!input) return message.SyntaxError();

		const urlRe = /^(?:https?:\/\/)?(?:m\.|www\.)?(?:youtu\.be\/|youtube\.com\/(?:embed\/|v\/|watch\?v=|watch\?.+&v=|shorts\/))((\w|-){11})(?:\S+)?$/;
		if (urlRe.test(input)) {
			const videoID = input.match(urlRe)[1];
			api.setMessageReaction("🐤", messageID, () => {}, true);
			if (type === "info") return fetchInfo(api, threadID, messageID, videoID);
			return handleDownload(api, threadID, messageID, videoID, type);
		}

		const cacheDir = path.join(__dirname, "cache");
		fs.ensureDirSync(cacheDir);
		const outPath = path.join(cacheDir, `ytc_${senderID}_${Date.now()}.png`);

		try {
			api.setMessageReaction("🐤", messageID, () => {}, true);

			const res = await axios.get(`${await baseApiUrl()}/api/ytb/search?q=${encodeURIComponent(input)}`);
			const results = (res.data.results || []).slice(0, MAX_RESULTS);
			if (!results.length) return api.sendMessage(`⭕ No results for "${input}"`, threadID, messageID);

			// user avatar for the "You" tab
			let avatarImg = null;
			try {
				let avUrl = null;
				if (usersData && usersData.getAvatarUrl) avUrl = await usersData.getAvatarUrl(senderID);
				if (!avUrl) avUrl = `https://graph.facebook.com/${senderID}/picture?width=512&height=512&access_token=6628568379%7Cc1e620fa708a1d5696fb991c1bde5662`;
				avatarImg = await getImg(avUrl);
			} catch (e) { avatarImg = null; }

			const buffer = await renderCanvas(input, results, avatarImg);
			fs.writeFileSync(outPath, buffer);

			api.sendMessage({
				body: `🔎 Results for: ${input}\n\nReply with a number (1-${results.length}) to get the ${type === "info" ? "info" : type}.`,
				attachment: fs.createReadStream(outPath)
			}, threadID, (err, info) => {
				if (fs.existsSync(outPath)) fs.unlinkSync(outPath);
				if (err || !info) return;
				global.GoatBot.onReply.set(info.messageID, {
					commandName,
					author: senderID,
					results,
					type,
					menuMessageID: info.messageID
				});
			}, messageID);
		} catch (e) {
			if (fs.existsSync(outPath)) fs.unlinkSync(outPath);
			return api.sendMessage("× Error: " + e.message, threadID, messageID);
		}
	},

	onReply: async function ({ event, api, Reply }) {
		const { results, type, author, menuMessageID } = Reply;
		if (event.senderID !== author) return;

		const choice = parseInt(event.body);
		if (isNaN(choice) || choice <= 0 || choice > results.length) return api.unsendMessage(menuMessageID);

		api.unsendMessage(menuMessageID);
		api.setMessageReaction("⌛", event.messageID, () => {}, true);
		if (type === "info") return fetchInfo(api, event.threadID, event.messageID, results[choice - 1].id);
		await handleDownload(api, event.threadID, event.messageID, results[choice - 1].id, type);
	}
