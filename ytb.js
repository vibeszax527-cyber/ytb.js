let fontsReady = false;

function ensureFonts() {
	if (fontsReady) return;
	try {
		fs.ensureDirSync(FONT_DIR);
		const p = path.join(FONT_DIR, "YTSans-bold.ttf");
		const buf = Buffer.from(FONT_BOLD_B64, "base64");
		if (!fs.existsSync(p) || fs.statSync(p).size !== buf.length) fs.writeFileSync(p, buf);
		if (Canvas.GlobalFonts) Canvas.GlobalFonts.registerFromPath(p, "YTSans");
		else Canvas.registerFont(p, { family: "YTSans", weight: "bold" });
	} catch (err) { console.log("[ytb] font setup failed:", err.message); }
	fontsReady = true;
}

