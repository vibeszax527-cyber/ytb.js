async function renderCanvas(query, results, userAvatarImg) {
	ensureFonts();
	const tpl = await getTemplate();
	const START_Y = 295;   // first thumbnail top (same as screenshot)
	const CARD_H = 570;    // 430 thumb + 140 text

	const canvas = createCanvas(W, 1620);
	const ctx = canvas.getContext("2d");
	ctx.fillStyle = "#ffffff";
	ctx.fillRect(0, 0, W, 1620);
	ctx.drawImage(tpl.top, 0, 0);          // status bar + search + chips
	ctx.drawImage(tpl.bottom, 0, 1452);    // bottom nav
	ctx.textBaseline = "alphabetic";
	ctx.textAlign = "left";

	/* ----- real-time clock ----- */
	ctx.fillStyle = "#000";
	ctx.font = `bold 38px ${FONT}`;
	ctx.fillText(dhakaTime(), 70, 58);

	/* ----- search text ----- */
	ctx.fillStyle = "#0f0f0f";
	ctx.font = `bold 29px ${FONT}`;
	ctx.fillText(fitText(ctx, query, 450), 119, 144);

	/* ----- result cards ----- */
	const thumbs = await Promise.all(results.map((r) => getImg(r.thumbnail)));
	ctx.font = `bold 30px ${FONT}`;
	const titleLines = results.map((r, i) => wrapTitle(ctx, `${i + 1}. ${r.title}`, W - 95 - 25, 2));

	for (let i = 0; i < results.length; i++) {
		const r = results[i];
		const y = START_Y + i * CARD_H;
		const ty = y + THUMB_H;

		// thumbnail
		ctx.save();
		ctx.beginPath(); ctx.rect(0, y, W, THUMB_H); ctx.clip();
		if (thumbs[i]) drawCover(ctx, thumbs[i], 0, y, W, THUMB_H);
		else { ctx.fillStyle = "#2b2b2b"; ctx.fillRect(0, y, W, THUMB_H); }
		ctx.restore();

		// duration badge
		if (r.time) {
			const label = String(r.time);
			ctx.font = `bold 24px ${FONT}`;
			const bw = ctx.measureText(label).width + 44, bh = 36;
			const bx = W - 15 - bw, by = y + THUMB_H - 15 - bh;
			rr(ctx, bx, by, bw, bh, 4); ctx.fillStyle = "rgba(0,0,0,0.82)"; ctx.fill();
			ctx.fillStyle = "#fff"; ctx.textAlign = "center";
			ctx.fillText(label, bx + bw / 2, by + 26); ctx.textAlign = "left";
		}

		// channel avatar (letter circle)
		const chName = (r.channel && r.channel.name) || (typeof r.channel === "string" ? r.channel : "Unknown");
		ctx.beginPath(); ctx.arc(45, ty + 65, 30, 0, Math.PI * 2); ctx.fillStyle = "#e5e5e5"; ctx.fill();
		ctx.fillStyle = "#606060"; ctx.font = `bold 28px ${FONT}`; ctx.textAlign = "center";
		ctx.fillText(String(chName).charAt(0).toUpperCase(), 45, ty + 75); ctx.textAlign = "left";

		// title
		const lines = titleLines[i];
		ctx.fillStyle = "#0f0f0f"; ctx.font = `bold 30px ${FONT}`;
		const tY = lines.length === 1 ? ty + 56 : ty + 46;
		lines.forEach((ln, li) => ctx.fillText(ln, 95, tY + li * 36));

		// channel name
		ctx.fillStyle = "#606060"; ctx.font = `bold 24px ${FONT}`;
		ctx.fillText(fitText(ctx, chName, W - 125), 95, lines.length === 1 ? ty + 101 : ty + 123);
	}

	/* ----- "You" tab = user's real DP ----- */
	ctx.save();
	ctx.beginPath(); ctx.arc(702, 1530, 26, 0, Math.PI * 2); ctx.closePath(); ctx.clip();
	if (userAvatarImg) drawCover(ctx, userAvatarImg, 676, 1504, 52, 52);
	else { ctx.fillStyle = "#cfcfcf"; ctx.fillRect(676, 1504, 52, 52); }
	ctx.restore();

	return canvas.toBuffer("image/png");
}

/* ---------------- download ---------------- */
async function handleDownload(api, threadID, messageID, videoID, type) {
	const format = type === "audio" ? "mp3" : "mp4";
	try {
		const res = await axios.get(`${await baseApiUrl()}/api/ytb/get?id=${videoID}&type=${type}`);
		const { title, downloadLink } = res.data.data;
		const response = await axios({ url: downloadLink, method: "GET", responseType: "stream" });
		const stream = response.data;
		stream.path = `yt_${Date.now()}.${format}`;
		api.sendMessage({ body: title, attachment: stream }, threadID, () => {
			api.setMessageReaction("✅", messageID, () => {}, true);
		}, messageID);
	} catch (e) {
		api.sendMessage("× Download failed: " + e.message, threadID, messageID);
	}
}

/* ---------------- info ---------------- */
async function fetchInfo(api, threadID, messageID, videoID) {
	try {
		const res = await axios.get(`${await baseApiUrl()}/api/ytb/details?id=${videoID}`);
		const d = res.data.details;
		const fmt = (n) => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ".");

		const msg = `💠 Title: ${d.title}\n🏪 Channel: ${d.channel}\n👨‍👩‍👧‍👦 Subscriber: ${fmt(d.subCount || 0)}\n⏱ Video duration: ${d.duration_raw || d.duration}\n👀 View count: ${fmt(d.view_count || 0)}\n👍 Like count: ${fmt(d.like_count || 0)}\n🆙 Upload date: ${d.upload_date || "N/A"}\n🔠 ID: ${videoID}\n🔗 Link: ${d.webpage_url}`;

		const cacheDir = path.join(__dirname, "cache");
		fs.ensureDirSync(cacheDir);
		const thumbPath = path.join(cacheDir, `info_${videoID}.jpg`);
		const thumbRes = await axios.get(d.thumbnail, { responseType: "arraybuffer" });
		fs.writeFileSync(thumbPath, Buffer.from(thumbRes.data));

		api.sendMessage({ body: msg, attachment: fs.createReadStream(thumbPath) }, threadID, () => {
			api.setMessageReaction("✅", messageID, () => {}, true);
			if (fs.existsSync(thumbPath)) fs.unlinkSync(thumbPath);
		}, messageID);
	} catch (e) {
		api.sendMessage("× Error: " + e.message, threadID, messageID);
	}
}

